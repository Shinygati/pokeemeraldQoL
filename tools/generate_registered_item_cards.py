"""Generate compact, uncompressed quick-item cards from native GBA icon assets.

Copy this file to tools/ in the ROM project and run it after building the native
item graphics when icons change. Normal ROM builds use the generated C header.
Only Python's standard library is required.
"""
from pathlib import Path
import re, struct

ROOT = Path(__file__).resolve().parents[1]
COLORS = [(0,0,0),(29,30,31),(3,4,5),(18,20,22),(8,18,29),(16,24,31),(8,10,12),(31,31,31),
          (27,5,6),(31,27,6),(12,23,10),(4,12,5),(18,11,5),(29,16,6),(5,8,19),(19,11,25)]

def card(icon=None, palette=None, selected=False):
    pixels = [[0]*32 for _ in range(32)]
    def rect(x,y,w,h,color):
        for yy in range(y,y+h):
            for xx in range(x,x+w): pixels[yy][xx]=color
    rect(4,0,24,32,4);rect(2,2,28,28,4);rect(0,4,32,24,4)
    rect(4,2,24,28,5);rect(2,4,28,24,5)
    rect(4,3,24,26,1);rect(3,4,26,24,1)
    if icon:
        assert len(icon)==288 and len(palette)==32
        words=struct.unpack('<16H',palette)
        source=[(v&31,(v>>5)&31,(v>>10)&31) for v in words]
        mapped=[0]+[min(range(1,16),key=lambda i:2*(rgb[0]-COLORS[i][0])**2+4*(rgb[1]-COLORS[i][1])**2+(rgb[2]-COLORS[i][2])**2) for rgb in source[1:]]
        for y in range(24):
            for x in range(24):
                sx=x;sy=y
                off=((sy//8)*3+sx//8)*32+(sy%8)*4+(sx%8)//2
                value=(icon[off]>>((sx&1)*4))&15
                if value:pixels[y+4][x+4]=mapped[value]
    if selected:
        for y in range(32):
            for x in range(32):
                if x < 3 or x >= 29 or y < 3 or y >= 29:
                    if pixels[y][x] == 4: pixels[y][x] = 8
                    elif pixels[y][x] == 5: pixels[y][x] = 13
    data=bytearray(512)
    for y in range(32):
        for x in range(32):
            off=((y//8)*4+x//8)*32+(y%8)*4+(x%8)//2
            data[off]|=pixels[y][x]<<((x&1)*4)
    return bytes(data)

def main():
    item_text=(ROOT/'src/data/items.h').read_text(encoding='utf-8')
    items=[m[1] for m in re.finditer(r'\[(ITEM_\w+)\]\s*=\s*\{(.*?)\n\s*\},',item_text,re.S) if re.search(r'\.pocket\s*=\s*POCKET_KEY_ITEMS',m[2])]
    table=dict((m[1],(m[2],m[3])) for m in re.finditer(r'\[(ITEM_\w+)\]\s*=\s*\{(\w+),\s*(\w+)\}',(ROOT/'src/data/item_icon_table.h').read_text()))
    assets=dict((m[1],m[2]) for m in re.finditer(r'const u32 (\w+)\[\]\s*=\s*INCBIN_U32\("([^"]+)"\)',(ROOT/'src/data/graphics/items.h').read_text()))
    graphics=[card()];selected_graphics=[card(selected=True)];lookup=[]
    for item in items:
        pic,pal=table[item]
        icon=(ROOT/assets[pic].removesuffix('.lz')).read_bytes()
        palette=(ROOT/assets[pal].removesuffix('.lz')).read_bytes()
        graphics.append(card(icon,palette));selected_graphics.append(card(icon,palette,True));lookup.append((item,len(graphics)-1))
    assert {'ITEM_MACH_BIKE','ITEM_ITEMFINDER','ITEM_EXP_SHARE','ITEM_SHINY_CHARM','ITEM_GOOD_ROD'} <= set(items)
    assert len(graphics)<256
    out=['// Generated by tools/generate_registered_item_cards.py. Prebuilt 32x32 cards; native 24x24 icons.',
         '// One shared BG palette avoids OBJ palette allocation and opening-time decompression.',
         'static const u16 sRegisteredCardPalette[16] = {']
    out+=['    '+', '.join(f'RGB({r}, {g}, {b})' for r,g,b in COLORS)+',','};',
          'static const u8 sRegisteredCardIds[ITEMS_COUNT] = {']
    out += [f'    [{item}] = {index},' for item,index in lookup]
    out+=['};','static const u32 sRegisteredCardGraphics[][128] = {']
    for data in graphics:
        words=struct.unpack('<128I',data);out.append('    {')
        for i in range(0,128,8):out.append('        '+', '.join(f'0x{x:08X}' for x in words[i:i+8])+',')
        out.append('    },')
    out+=['};','static const u32 sRegisteredCardSelectedGraphics[][128] = {']
    for data in selected_graphics:
        words=struct.unpack('<128I',data);out.append('    {')
        for i in range(0,128,8):out.append('        '+', '.join(f'0x{x:08X}' for x in words[i:i+8])+',')
        out.append('    },')
    out+=['};','']
    (ROOT/'src/data/registered_item_cards.h').write_text('\n'.join(out),encoding='utf-8',newline='\n')
    print(f'Generated {len(items)} Key Item cards, all with nonblank cached icons. {len(graphics)*512} ROM bytes.')

if __name__=='__main__': main()
